# ============================================================
# 7. OrderController.java — @RequestHeader + ветка
# ============================================================
info "7/8 OrderController.java — Idempotency-Key"
CTRL="$SRC/controller/OrderController.java"
if grep -q "Idempotency-Key" "$CTRL"; then
  warn "Idempotency-Key уже обрабатывается, пропуск"
else
  # 1) добавить параметр @RequestHeader в сигнатуру create()
  #    исходно: public ResponseEntity<?> create(@AuthenticationPrincipal AuthenticatedUser principal,
  #                                             @Valid @RequestBody CreateOrderRequest req) {
  perl -0777 -i -pe '
    s/(public\s+ResponseEntity<\?>\s+create\s*\(\s*@AuthenticationPrincipal\s+AuthenticatedUser\s+principal\s*,)
     (\s*)(\@Valid\s+\@RequestBody\s+CreateOrderRequest\s+req\s*\))/$1
$2\@RequestHeader(value = "Idempotency-Key", required = false) String idemKey,
$2$3/xs;
  ' "$CTRL"

  # 2) вставить идемпотентную ветку перед существующим вызовом orderService.create(...)
  perl -0777 -i -pe '
    s/(\n\s*)(OrderResponse\s+r\s*=\s*orderService\.create\()/
$1if (idemKey != null \&\& !idemKey.isBlank()) {$1    return orderService.createIdempotent(principal.id(), req, idemKey.trim());$1}$1$2/xs;
  ' "$CTRL"

  # 3) добавить import Map (если ещё нет)
  if ! grep -q "^import java.util.Map;" "$CTRL"; then
    # берём из java.util.List, если есть, иначе добавляем
    if grep -q "^import java.util.List;" "$CTRL"; then
      perl -i -pe 's/^import java\.util\.List;/import java.util.List;\nimport java.util.Map;/' "$CTRL"
    else
      # вставляем после последнего import
      awk 'BEGIN{done=0} /^import /{print; last=NR; next} {if(!done&&last>0){print "import java.util.Map;";done=1} print} END{if(!done&&last>0)print "import java.util.Map;"}' "$CTRL" > "$CTRL.tmp" && mv "$CTRL.tmp" "$CTRL"
    fi
  fi
  info "OrderController обновлён"
fi

