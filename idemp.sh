#!/usr/bin/env bash
# shop/apply-idempotency.sh
#
# Вносит все изменения для Idempotency-Key в order-service.
# Идемпотентен: повторный запуск не дублирует код.
# Перед правкой существующих файлов делает backup в /tmp/shop-idempotency-backup-<ts>/
#
set -euo pipefail
cd "$(dirname "$0")"

RED=$'\033[0;31m'; GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'; NC=$'\033[0m'
info() { echo "${GREEN}▶${NC} $*"; }
warn() { echo "${YELLOW}⚠${NC} $*"; }
fail() { echo "${RED}✗${NC} $*" >&2; exit 1; }

ORDER_DIR="order-service"
SRC="$ORDER_DIR/src/main/java/com/example/shop/order"
RES="$ORDER_DIR/src/main/resources"
BACKUP="/tmp/shop-idempotency-backup-$(date +%Y%m%d-%H%M%S)"

[[ -d "$ORDER_DIR" ]] || fail "Не найден $ORDER_DIR. Запустите из корня репозитория shop/."

mkdir -p "$BACKUP"
info "Backup: $BACKUP"

# Сохраняем существующие файлы, которые будем менять
for f in \
  "$RES/db/changelog/db.changelog-master.yaml" \
  "$SRC/controller/OrderController.java" \
  "$SRC/service/OrderService.java" \
  "$SRC/OrderServiceApplication.java"
do
  [[ -f "$f" ]] && mkdir -p "$BACKUP/$(dirname "$f")" && cp "$f" "$BACKUP/$f"
done

# ---------- утилита: записать файл, если ещё не создан этим скриптом ----------
write_new() {
  local path="$1"
  if [[ -f "$path" ]] && grep -q "GENERATED BY apply-idempotency.sh" "$path" 2>/dev/null; then
    warn "уже создан ранее, пропуск: $path"
    return 0
  fi
  if [[ -f "$path" ]]; then
    fail "Файл уже существует и создан не этим скриптом: $path. Удалите вручную или переименуйте."
  fi
  mkdir -p "$(dirname "$path")"
  cat > "$path"
  info "создан: $path"
}

