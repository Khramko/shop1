# 8. OrderService.java — createIdempotent + поля в конструкторе
# ============================================================
info "8/8 OrderService.java — createIdempotent"
SVC="$SRC/service/OrderService.java"
if grep -q "createIdempotent" "$SVC"; then
  warn "createIdempotent уже есть, пропуск"
else
  # 1) добавить import-ы
  if ! grep -q "import com.example.shop.order.model.IdempotencyKey;" "$SVC"; then
    perl -i -pe 's{^import com\.example\.shop\.order\.model\.Order;$}{import com.example.shop.order.model.IdempotencyKey;\nimport com.example.shop.order.model.Order;}' "$SVC"
  fi
  if ! grep -q "import com.example.shop.order.repository.IdempotencyKeyRepository;" "$SVC"; then
    perl -i -pe 's{^import com\.example\.shop\.order\.repository\.OrderRepository;$}{import com.example.shop.order.repository.IdempotencyKeyRepository;\nimport com.example.shop.order.repository.OrderRepository;}' "$SVC"
  fi
  if ! grep -q "import com.example.shop.order.dto.CreateOrderRequest;" "$SVC"; then
    perl -i -pe 's{^import com\.example\.shop\.order\.dto\.OrderResponse;$}{import com.example.shop.order.dto.CreateOrderRequest;\nimport com.example.shop.order.dto.OrderResponse;}' "$SVC"
  fi
  if ! grep -q "import com.fasterxml.jackson.core.JsonProcessingException;" "$SVC"; then
    perl -i -pe 's{^import org\.springframework\.beans\.factory\.annotation\.Value;$}{import com.fasterxml.jackson.core.JsonProcessingException;\nimport com.fasterxml.jackson.databind.ObjectMapper;\nimport org.springframework.beans.factory.annotation.Value;}' "$SVC"
  fi
  if ! grep -q "import org.springframework.dao.DataIntegrityViolationException;" "$SVC"; then
    perl -i -pe 's{^import org\.springframework\.kafka\.core\.KafkaTemplate;$}{import org.springframework.dao.DataIntegrityViolationException;\nimport org.springframework.http.HttpStatus;\nimport org.springframework.http.ResponseEntity;\nimport org.springframework.kafka.core.KafkaTemplate;}' "$SVC"
  fi
  if ! grep -q "import java.util.Optional;" "$SVC"; then
    perl -i -pe 's{^import java\.util\.List;$}{import java.util.List;\nimport java.util.Optional;}' "$SVC"
  fi

  # 2) добавить поля
  if ! grep -q "private final IdempotencyKeyRepository idemRepo;" "$SVC"; then
    perl -i -pe 's{^(\s*)private final SagaStateRepository sagaRepo;$}{$1private final SagaStateRepository sagaRepo;\n$1private final IdempotencyKeyRepository idemRepo;\n$1private final ObjectMapper objectMapper;}' "$SVC"
  fi

  # 3) расширить конструктор
  perl -0777 -i -pe '
    s/(public\s+OrderService\s*\(\s*OrderRepository\s+orderRepository\s*,\s*SagaStateRepository\s+sagaRepo\s*,)
     (\s*OrderEventPublisher\s+v1Publisher\s*,\s*KafkaTemplate<String,\s*Object>\s+kafka\s*\))/$1\n$2IdempotencyKeyRepository idemRepo,\n$2ObjectMapper objectMapper$2/xs;
  ' "$SVC"

  # 4) присвоить поля в конструкторе (после this.sagaRepo = sagaRepo;)
  perl -i -pe 's{^(\s*)this\.sagaRepo = sagaRepo;$}{$1this.sagaRepo = sagaRepo;\n$1this.idemRepo = idemRepo;\n$1this.objectMapper = objectMapper;}' "$SVC"

  # 5) вставить метод createIdempotent перед createSaga
  NEW_METHOD=$(cat <<'METHOD'

    // ============================================================
    //  Idempotent create с Idempotency-Key
    // ============================================================
    @Transactional
    public ResponseEntity<?> createIdempotent(Long userId, CreateOrderRequest req, String idemKey) {
        // 1. Быстрый путь: ключ уже есть → отдаём сохранённый ответ
        Optional<IdempotencyKey> existing = idemRepo.findByUserIdAndIdempotencyKey(userId, idemKey);
        if (existing.isPresent()) {
            IdempotencyKey k = existing.get();
            log.info("Idempotent replay userId={} key={} orderId={}", userId, idemKey, k.getOrderId());
            return ResponseEntity.status(k.getHttpStatus())
                    .header("X-Idempotent-Replay", "true")
                    .header("Content-Type", "application/json")
                    .body(k.getResponseBody());
        }

        // 2. Создаём заказ
        OrderResponse r = create(userId, req.getPrice(), req.getSku(), req.getQty(), req.getDeliverySlot());

        // 3. Сериализуем ответ
        String bodyJson;
        try {
            bodyJson = objectMapper.writeValueAsString(r);
        } catch (JsonProcessingException ex) {
            throw new IllegalStateException("Cannot serialize order response", ex);
        }

        // 4. Сохраняем ключ; при гонке — читаем уже вставленный
        try {
            idemRepo.save(new IdempotencyKey(userId, idemKey, r.getOrderId(), bodyJson, 202));
        } catch (DataIntegrityViolationException race) {
            log.warn("Idempotency race userId={} key={} — reading existing", userId, idemKey);
            IdempotencyKey k = idemRepo.findByUserIdAndIdempotencyKey(userId, idemKey)
                    .orElseThrow(() -> new IllegalStateException("Idempotency key vanished after race"));
            return ResponseEntity.status(k.getHttpStatus())
                    .header("X-Idempotent-Replay", "true")
                    .header("Content-Type", "application/json")
                    .body(k.getResponseBody());
        }

        return ResponseEntity.status(HttpStatus.ACCEPTED).body(r);
    }

METHOD
)
  perl -0777 -i -pe "s{(    private OrderResponse createSaga\()}{$NEW_METHOD\$1}" "$SVC"
  info "OrderService.createIdempotent добавлен"
fi

